import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(repositoryRoot, 'docs/tooling.md');
const packageJson = JSON.parse(
  readFileSync(resolve(repositoryRoot, 'package.json'), 'utf8'),
);
const packageLock = JSON.parse(
  readFileSync(resolve(repositoryRoot, 'package-lock.json'), 'utf8'),
);

function commandOutput(command, args, versionPattern) {
  const result = spawnSync(command, args, {
    cwd: repositoryRoot,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'ignore'],
  });

  if (result.error || result.status !== 0) {
    return 'not detected';
  }

  const output = result.stdout.trim();

  if (!output) {
    return 'not detected';
  }

  const match = output.match(versionPattern);
  return match?.[1] ?? output.split('\n')[0];
}

function lockedPackageVersion(packageName) {
  const entry = packageLock.packages?.[`node_modules/${packageName}`];

  if (!entry?.version) {
    throw new Error(`${packageName} is missing from package-lock.json`);
  }

  return entry.version;
}

function major(version) {
  return version.replace(/^v/, '').split('.')[0];
}

function majorMinor(version) {
  return version.replace(/^v/, '').split('.').slice(0, 2).join('-');
}

function npmVersion() {
  const runtimeVersion = process.env.npm_config_user_agent?.match(
    /(?:^|\s)npm\/([0-9]+(?:\.[0-9]+)+)/,
  )?.[1];
  const probedVersion = commandOutput(
    'npm',
    ['--version'],
    /([0-9]+(?:\.[0-9]+)+)/,
  );
  const declaredVersion = packageJson.packageManager?.match(
    /^npm@([0-9]+(?:\.[0-9]+)+)$/,
  )?.[1];

  if (runtimeVersion) {
    return runtimeVersion;
  }

  return probedVersion === 'not detected'
    ? (declaredVersion ?? probedVersion)
    : probedVersion;
}

